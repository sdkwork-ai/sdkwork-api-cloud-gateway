#!/usr/bin/env bash
# scripts/deploy/generate-nginx-conf.sh
#
# Render nginx reverse-proxy site configs for every environment into docker/nginx/.
# Pure generation: no docker, no root. Idempotent (overwrites the committed conf).
#
# One file per environment (named after the canonical host, e.g. api-dev.sdkwork.com.conf)
# carries ALL three public domains as `server_name` aliases, so a single nginx on port 80
# routes every environment by Host header with zero port conflicts.
#
# HTTP (80) and HTTPS (443) are BOTH enabled for every environment. Production upgrades
# plain HTTP to HTTPS (301); dev/test/staging answer on both so clients can use either.
#
# Usage:
#   bash scripts/deploy/generate-nginx-conf.sh            # all environments
#   bash scripts/deploy/generate-nginx-conf.sh development test
#   bash scripts/deploy/generate-nginx-conf.sh all
set -euo pipefail

SCRIPT_DIR=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
# shellcheck source=lib/common.sh
source "$SCRIPT_DIR/lib/common.sh"
# shellcheck source=lib/environments.sh
source "$SCRIPT_DIR/lib/environments.sh"

repo_root=$(deploy_repo_root)
nginx_dir="$repo_root/docker/nginx"

# Emit the shared proxy_pass block (quoted heredoc => nginx literal $vars).
emit_proxy_block() {
  cat <<'PROXY'
        proxy_http_version 1.1;
        proxy_set_header Host $host;
        proxy_set_header X-Forwarded-Host $host;
        proxy_set_header X-Forwarded-Proto $scheme;
        proxy_set_header X-Real-IP $remote_addr;
        proxy_set_header X-Forwarded-For $proxy_add_x_forwarded_for;
        proxy_set_header Upgrade $http_upgrade;
        proxy_set_header Connection "upgrade";
        proxy_buffering off;
        proxy_read_timeout 300s;
        proxy_send_timeout 300s;
        client_max_body_size 1100m;
PROXY
}

render_one() {
  local env=$1
  local port canonical names cert_dir access_log error_log
  port=$(env_host_port "$env")
  canonical=$(env_canonical_host "$env")
  names=$(env_server_names "$env")
  cert_dir=$(cert_host_dir "$env")
  access_log="/var/log/nginx/$canonical.access.log"
  error_log="/var/log/nginx/$canonical.error.log"

  local out="$nginx_dir/$canonical.conf"
  {
    echo "# $canonical (+ aliases) -> $env container gateway (host port $port)."
    echo "# Generated by scripts/deploy/generate-nginx-conf.sh — do not edit by hand."
    echo "# Install path: /etc/nginx/sites-enabled/sdkwork/$canonical.conf"
    echo "# HTTP (80) + HTTPS (443) enabled. Certs: $cert_dir/{fullchain,privkey}.pem"
    echo
    echo "server {"
    echo "    listen 80;"
    echo "    listen [::]:80;"
    echo "    server_name $names;"
    echo
    echo "    access_log $access_log;"
    echo "    error_log  $error_log;"
    echo

    if [[ "$env" == "production" ]]; then
      # Production: terminate ACME challenges and upgrade HTTP -> HTTPS (secure by default).
      echo "    location /.well-known/acme-challenge/ { root /var/www/certbot; }"
      echo
      echo "    location / { return 301 https://\$host\$request_uri; }"
      echo "}"
      echo
      echo "server {"
      echo "    listen 443 ssl http2;"
      echo "    listen [::]:443 ssl http2;"
      echo "    server_name $names;"
      echo
      echo "    ssl_certificate $cert_dir/fullchain.pem;"
      echo "    ssl_certificate_key $cert_dir/privkey.pem;"
      echo "    ssl_protocols TLSv1.2 TLSv1.3;"
      echo
      echo "    access_log $access_log;"
      echo "    error_log  $error_log;"
      echo
      echo "    location / {"
      echo "        proxy_pass http://127.0.0.1:$port;"
      emit_proxy_block
      echo "    }"
      echo "}"
    else
      # Non-production: answer on 80 directly (so HTTP works) AND on 443 (HTTPS).
      echo "    location / {"
      echo "        proxy_pass http://127.0.0.1:$port;"
      emit_proxy_block
      echo "    }"
      echo "}"
      echo
      echo "server {"
      echo "    listen 443 ssl http2;"
      echo "    listen [::]:443 ssl http2;"
      echo "    server_name $names;"
      echo
      echo "    ssl_certificate $cert_dir/fullchain.pem;"
      echo "    ssl_certificate_key $cert_dir/privkey.pem;"
      echo "    ssl_protocols TLSv1.2 TLSv1.3;"
      echo
      echo "    access_log $access_log;"
      echo "    error_log  $error_log;"
      echo
      echo "    location / {"
      echo "        proxy_pass http://127.0.0.1:$port;"
      emit_proxy_block
      echo "    }"
      echo "}"
    fi
  } > "$out"

  log_ok "wrote $out"
}

main() {
  local targets
  targets=($(parse_env_selection "$@"))
  log_step "generating nginx site configs: ${targets[*]}"
  for env in "${targets[@]}"; do render_one "$env"; done
  log_info "next: install with 'bash scripts/deploy/apply.sh' (copies to /etc/nginx/sites-enabled/sdkwork/)"
}

main "$@"
